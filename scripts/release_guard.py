"""Jason Stys: BKW-only exact-main prerequisites and non-overwriting numeric-ID draft delivery.

The helper never publishes, deletes, edits or retargets a release. Source/analysis
reads fail closed; only prepare creates a fresh draft and upload attaches exact
tested platform files. Variable/function locations are generated by code_index.py.
"""

import argparse
import hashlib
import http.client
import json
import os
import re
import stat
import subprocess
import tomllib
from pathlib import Path
from urllib.parse import quote

if __package__:
    from .draft_lookup import find_release, read_by_id, release_id, require
else:
    from draft_lookup import find_release, read_by_id, release_id, require

ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = "JasonStys/business-knowledge-workbench"
BASE = f"repos/{REPOSITORY}"
VERSION = "1.4.1"
WORKFLOWS = ("ci.yml", "packages.yml", "codeql.yml")
CATEGORIES = {
    ".github/workflows/codeql.yml:analyze/language:python",
    ".github/workflows/codeql.yml:analyze/language:javascript-typescript",
}
MAX_JSON = 2 * 1024 * 1024
MAX_ASSET = 1024**3


def strict_json(raw: bytes | str):
    """Reject duplicate/nonfinite identity fields rather than silently replacing checked values."""

    def pairs(items):
        result = dict(items)
        require(len(result) == len(items), "Duplicate metadata key")
        return result

    def invalid_constant(_):
        raise ValueError("Nonfinite metadata")

    return json.loads(raw, object_pairs_hook=pairs, parse_constant=invalid_constant)


def headers() -> dict[str, str]:
    """Read the job's scoped ephemeral token; never print it or place it in command arguments."""
    token = os.environ.get("GH_TOKEN", "")
    require(bool(token) and "\r" not in token and "\n" not in token, "Scoped GitHub token required")
    return {
        "Authorization": "Bearer " + token,
        "User-Agent": "bkw-release-guard",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }


def api(endpoint: str, *, body: dict | None = None, missing: bool = False):
    """Fixed API host, no redirects/retries, bounded JSON and an actual HTTP404-only absence result."""
    require(
        endpoint.startswith(BASE + "/") and "\r" not in endpoint and "\n" not in endpoint,
        "Foreign API namespace",
    )
    connection = http.client.HTTPSConnection("api.github.com", timeout=30)
    try:
        data = None if body is None else json.dumps(body).encode("utf-8")
        request_headers = headers()
        if data is not None:
            request_headers["Content-Type"] = "application/json"
        connection.request("GET" if body is None else "POST", "/" + endpoint, data, request_headers)
        response = connection.getresponse()
        raw = response.read(MAX_JSON + 1)
        require(len(raw) <= MAX_JSON, "GitHub metadata exceeds its byte budget")
        if missing and response.status == 404:
            return None
        require(
            response.status == (200 if body is None else 201),
            f"GitHub metadata request failed with HTTP{response.status}",
        )
        return strict_json(raw)
    finally:
        connection.close()


def complete_list(endpoint: str) -> list:
    """Read complete small metadata collections or refuse ambiguity at the fixed500-row bound."""
    result = []
    for page in range(1, 6):
        rows = api(f"{endpoint}&per_page=100&page={page}")
        require(isinstance(rows, list) and len(rows) <= 100, "Malformed metadata page")
        result.extend(rows)
        if len(rows) < 100:
            return result
    raise ValueError("Metadata collection exceeds complete review bound")


def require_source(source: str) -> None:
    """Require actual current-main push lanes, full-main processed analyses and no open-main alerts."""
    require(
        api(BASE + "/git/ref/heads/main").get("object", {}).get("sha") == source,
        "Main moved; validate the new source",
    )
    for workflow in WORKFLOWS:
        value = api(f"{BASE}/actions/workflows/{workflow}/runs?head_sha={source}&per_page=100")
        rows = value.get("workflow_runs")
        require(
            isinstance(rows, list)
            and 0 < len(rows) < 100
            and type(value.get("total_count")) is int
            and value["total_count"] == len(rows),
            "Incomplete source workflow history",
        )
        for row in rows:
            require(
                row.get("head_sha") == source
                and row.get("status") == "completed"
                and row.get("conclusion") == "success"
                and row.get("path") == f".github/workflows/{workflow}"
                and row.get("repository", {}).get("full_name") == REPOSITORY,
                "Unsuccessful or differently sourced prerequisite workflow",
            )
        require(
            sum(row.get("event") == "push" and row.get("head_branch") == "main" for row in rows)
            == 1,
            "Exactly one successful main-push run required for each prerequisite",
        )
    current = [
        row
        for row in complete_list(BASE + "/code-scanning/analyses?ref=refs%2Fheads%2Fmain")
        if row.get("commit_sha") == source
    ]
    require(
        len(current) == 2 and {row.get("category") for row in current} == CATEGORIES,
        "Both exact-source full-main CodeQL categories required",
    )
    for row in current:
        require(
            row.get("ref") == "refs/heads/main"
            and row.get("analysis_key") == ".github/workflows/codeql.yml:analyze"
            and row.get("tool", {}).get("name") == "CodeQL"
            and row.get("error") == ""
            and row.get("warning") == ""
            and type(row.get("id")) is int
            and row["id"] > 0
            and type(row.get("rules_count")) is int
            and row["rules_count"] > 0,
            "Incomplete/error-bearing/unprocessed CodeQL analysis",
        )
    require(
        not complete_list(BASE + "/code-scanning/alerts?ref=refs%2Fheads%2Fmain&state=open"),
        "Open main CodeQL alerts require review/correction",
    )


def no_tag() -> None:
    """A public Git tag is immutable for this helper; only proven404 absence authorizes draft work."""
    require(
        api(f"{BASE}/git/ref/tags/v{VERSION}", missing=True) is None,
        "Version tag already exists; published versions are immutable",
    )


def context() -> str:
    """Use the clean exact checked-out main SHA and coherent product manifests, never a mutable input alias."""
    require(
        os.environ.get("GITHUB_REPOSITORY") == REPOSITORY
        and os.environ.get("GITHUB_EVENT_NAME") == "workflow_dispatch"
        and os.environ.get("GITHUB_REF") == "refs/heads/main",
        "Only trusted-main manual delivery is allowed",
    )
    package = strict_json((ROOT / "package.json").read_bytes())
    lock = strict_json((ROOT / "package-lock.json").read_bytes())
    python = tomllib.loads((ROOT / "pyproject.toml").read_text("utf-8"))
    require(
        package.get("version")
        == python["project"]["version"]
        == lock.get("version")
        == lock.get("packages", {}).get("", {}).get("version")
        == VERSION,
        "Fresh1.4.1 product and lockfile identities must agree",
    )
    source = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
        timeout=10,
    ).stdout.strip()
    require(re.fullmatch("[a-f0-9]{40}", source) is not None, "Exact source SHA required")
    require(
        subprocess.run(
            ["git", "status", "--porcelain"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
            timeout=10,
        ).stdout
        == "",
        "Dirty release source refused",
    )
    expected = os.environ.get("EXPECTED_SOURCE_SHA", source)
    require(expected == source, "Prepared source changed")
    return source


def draft(identifier: int, source: str) -> dict:
    """Reread the prepared numeric ID and refuse publication, retargeting, ID/tag swaps or tag creation."""
    record = read_by_id(api, REPOSITORY, identifier)
    require(
        record["tag_name"] == "v" + VERSION
        and record["target_commitish"] == source
        and record["draft"] is True
        and record["prerelease"] is False,
        "Prepared draft identity changed",
    )
    no_tag()
    return record


def names(system: str) -> list[str]:
    """Preserve each platform's existing installer/archive plus two sidecars, twelve assets total."""
    payloads = {
        "Windows": [
            f"Business Knowledge Workbench Setup {VERSION}.exe",
            f"BusinessKnowledgeWorkbench-{VERSION}-windows-x64.zip",
        ],
        "Linux": [
            f"Business Knowledge Workbench-{VERSION}.AppImage",
            f"BusinessKnowledgeWorkbench-{VERSION}-linux-x64.tar.gz",
        ],
        "macOS": [
            f"Business Knowledge Workbench-{VERSION}-arm64.dmg",
            f"BusinessKnowledgeWorkbench-{VERSION}-macos-arm64.tar.gz",
        ],
    }
    require(system in payloads, "Unsupported platform")
    return [item for payload in payloads[system] for item in (payload, payload + ".sha256")]


def attached(record: dict, *, complete: bool = False) -> dict:
    """Reject unexpected/colliding/starter assets; strict checks are safe because uploads are serialized."""
    expected = {
        name.replace(" ", ".") for system in ("Windows", "Linux", "macOS") for name in names(system)
    }
    result = {}
    identifiers = set()
    for row in record["assets"]:
        name = row.get("name")
        require(
            name in expected
            and name not in result
            and type(row.get("id")) is int
            and 0 < row["id"] < 2**63
            and row["id"] not in identifiers,
            "Unexpected/duplicate asset identity",
        )
        require(
            type(row.get("size")) is int
            and 0 < row["size"] <= MAX_ASSET
            and row.get("state") == "uploaded"
            and isinstance(row.get("digest"), str)
            and re.fullmatch("sha256:[a-f0-9]{64}", row["digest"]) is not None,
            "Incomplete asset or missing provider digest",
        )
        result[name] = row
        identifiers.add(row["id"])
    require(not complete or set(result) == expected, "All twelve tested assets required")
    return result


def upload_bytes(identifier: int, stream, name: str, size: int, digest: str) -> dict:
    """Stream a checked descriptor to the fixed uploads host; never follow metadata URLs or overwrite."""
    connection = http.client.HTTPSConnection("uploads.github.com", timeout=60)
    try:
        connection.putrequest(
            "POST", f"/{BASE}/releases/{identifier}/assets?name={quote(name, safe='')}"
        )
        for key, value in {
            **headers(),
            "Content-Type": "application/octet-stream",
            "Content-Length": str(size),
        }.items():
            connection.putheader(key, value)
        connection.endheaders()
        remaining = size
        while remaining:
            block = stream.read(min(65536, remaining))
            require(bool(block), "Payload changed during upload")
            connection.send(block)
            remaining -= len(block)
        require(stream.read(1) == b"", "Payload grew during upload")
        response = connection.getresponse()
        raw = response.read(MAX_JSON + 1)
        require(
            len(raw) <= MAX_JSON and response.status == 201,
            "Upload failed; draft retained for review",
        )
        row = strict_json(raw)
        require(
            row.get("name") == name
            and row.get("size") == size
            and row.get("state") == "uploaded"
            and row.get("digest") == "sha256:" + digest,
            "Uploaded identity/digest mismatch",
        )
        return row
    finally:
        connection.close()


def open_output(path: Path, limit: int = MAX_ASSET):
    """Open one no-follow bounded regular descriptor, rejecting aliases and FIFO swaps."""
    require(not path.is_symlink(), "Build output may not be a symbolic link")
    flags = (
        os.O_RDONLY
        | getattr(os, "O_BINARY", 0)
        | getattr(os, "O_NOFOLLOW", 0)
        | getattr(os, "O_NONBLOCK", 0)
    )
    descriptor = os.open(path, flags)
    try:
        info = os.fstat(descriptor)
        require(
            stat.S_ISREG(info.st_mode) and info.st_nlink == 1 and 0 < info.st_size <= limit,
            "Build output must be a bounded single-link regular file",
        )
        return os.fdopen(descriptor, "rb")
    except BaseException:
        os.close(descriptor)
        raise


def file_hash(stream, size: int) -> str:
    """Hash only the declared checked byte budget and refuse shrink/growth; never read until arbitrary EOF."""
    digest = hashlib.sha256()
    remaining = size
    while remaining:
        block = stream.read(min(65536, remaining))
        require(bool(block), "Build output shrank during hashing")
        digest.update(block)
        remaining -= len(block)
    require(stream.read(1) == b"", "Build output grew during hashing")
    return digest.hexdigest()


def upload(identifier: int, source: str, system: str) -> None:
    """Preflight every sidecar, then attach fixed platform files without replacing any existing asset."""
    folder = ROOT / "release/installers"
    planned = names(system)
    existing = attached(draft(identifier, source))
    require(
        not any(name.replace(" ", ".") in existing for name in planned),
        "Asset already exists; no clobber",
    )
    verified = {}
    for name in planned:
        path = folder / name
        with open_output(path, 512 if name.endswith(".sha256") else MAX_ASSET) as stream:
            size = os.fstat(stream.fileno()).st_size
            verified[name] = (size, file_hash(stream, size))
    for name in planned[::2]:
        with open_output(folder / (name + ".sha256"), 512) as stream:
            raw = stream.read(513)
        expected = verified[name][1] + "  " + name.replace(" ", ".") + "\n"
        require(
            raw.decode("ascii") in (expected, expected.replace("\n", "\r\n")),
            "Payload checksum mismatch",
        )
    for name in planned:
        normalized = name.replace(" ", ".")
        require(
            normalized not in attached(draft(identifier, source)),
            "Upload collision; draft retained",
        )
        path = folder / name
        with open_output(path) as stream:
            info = os.fstat(stream.fileno())
            digest = file_hash(stream, info.st_size)
            require(
                (info.st_size, digest) == verified[name],
                "Build output changed after checksum preflight",
            )
            stream.seek(0)
            upload_bytes(identifier, stream, normalized, info.st_size, digest)
            observed = attached(draft(identifier, source)).get(normalized)
            require(
                observed is not None
                and observed["digest"] == "sha256:" + digest
                and observed["size"] == info.st_size,
                "Published draft bytes differ from the local payload",
            )


def main() -> None:
    """Prepare/upload/verify only; independent downloaded application acceptance precedes owner publication."""
    parser = argparse.ArgumentParser()
    parser.add_argument("operation", choices=("prepare", "upload", "verify"))
    operation = parser.parse_args().operation
    source = context()
    if operation == "prepare":
        require_source(source)
        no_tag()
        require(
            find_release(api, REPOSITORY, "v" + VERSION, missing=True) is None,
            "This version already has a draft/release",
        )
        notes = ROOT / f"docs/releases/v{VERSION}.md"
        require(
            notes.is_file() and notes.stat().st_size <= 65536,
            "Bounded current release notes required",
        )
        created = api(
            BASE + "/releases",
            body={
                "tag_name": "v" + VERSION,
                "target_commitish": source,
                "draft": True,
                "prerelease": False,
                "name": "Business Knowledge Workbench " + VERSION,
                "body": notes.read_text("utf-8"),
            },
        )
        record = draft(release_id(created.get("id")), source)
        require(not record["assets"], "Fresh draft unexpectedly has assets")
        with Path(os.environ["GITHUB_OUTPUT"]).open("a", encoding="utf-8") as output:
            output.write(f"sha={source}\nrelease_id={record['id']}\n")
        return
    raw = os.environ.get("EXPECTED_RELEASE_ID", "")
    require(
        re.fullmatch("[1-9][0-9]{0,18}", raw) is not None, "Prepared numeric release ID required"
    )
    identifier = release_id(int(raw))
    if operation == "upload":
        upload(identifier, source, os.environ.get("RUNNER_OS", ""))
    else:
        require_source(source)
        attached(draft(identifier, source), complete=True)
        print(
            json.dumps(
                {
                    "source": source,
                    "version": VERSION,
                    "release_id": identifier,
                    "assets": 12,
                    "draft": True,
                    "publication": "pending independent downloaded acceptance",
                }
            )
        )


if __name__ == "__main__":
    main()
